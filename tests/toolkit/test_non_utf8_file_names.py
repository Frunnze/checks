"""
A source file whose name is not valid UTF-8 must not crash a Python
finder. Domain: a clean module user-service/src/caf<byte>.py whose name
carries one generated byte from 0x80-0xff (never valid UTF-8 on its own),
staged in git, checked by the Python finders that read the file list.
Oracle: postcondition - clean code passes, and no finder dies with a
traceback.

Concrete inputs -> expected outputs:
- input: user-service/src/cafe.py = "VALUE = 1", open-closed
  output: exit 0.
- input (falsifying example, pinned as @example): user-service/src/caf\\xe9.py
  = "VALUE = 1", open-closed
  output: expected exit 0, got exit 1 with "UnicodeDecodeError: 'utf-8'
  codec can't decode byte 0xe9" - dependency-inversion and
  nested-definitions died the same way.
"""

import os
import subprocess
import tempfile
from pathlib import Path

import pytest
from hypothesis import example, given, settings
from hypothesis import strategies as st

from check_support import link_real_python, repository, run_check

FINDER_CHECKS = ("open-closed", "dependency-inversion", "nested-definitions")
NON_UTF8_NAME = os.fsdecode(b"caf\xe9.py")


def _file_system_accepts_non_utf8_names() -> bool:
    with tempfile.TemporaryDirectory() as directory:
        probe = Path(directory) / NON_UTF8_NAME

        try:
            probe.touch()
        except OSError:
            return False

    return True


pytestmark = pytest.mark.skipif(
    not _file_system_accepts_non_utf8_names(),
    reason="the file system refuses file names that are not UTF-8",
)


@given(
    check_name=st.sampled_from(FINDER_CHECKS),
    byte=st.integers(min_value=0x80, max_value=0xFF),
)
@example(check_name="open-closed", byte=0xE9)
@settings(max_examples=4, deadline=None)
def test_finder_property_reads_a_file_name_that_is_not_utf8(
    check_name: str, byte: int
) -> None:
    module = os.fsdecode(b"user-service/src/caf" + bytes([byte]) + b".py")

    with tempfile.TemporaryDirectory() as directory:
        project = Path(directory)
        repository(project)
        link_real_python(project)
        source = project / module
        source.parent.mkdir(parents=True)
        _ = source.write_text("VALUE = 1\n", encoding="utf-8")
        _ = subprocess.run(["git", "add", "-A"], cwd=project, check=True)
        finished = run_check(project, check_name)

    assert "Traceback" not in finished.stderr, finished.stderr
    assert finished.returncode == 0, finished.stderr
